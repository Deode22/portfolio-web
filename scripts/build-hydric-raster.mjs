/**
 * GeoTIFF -> colormapped RGBA PNG + generated manifest for the hydric layer.
 *
 * Same pipeline as the RUSLE bake (scripts/lib/), different display rules:
 * the source is a Google Earth Engine ΔNDMI export, BigTIFF + tiled LZW
 * float32 with no GDAL_NODATA tag — cells that were masked in GEE arrive as
 * NaN and simply fail the finite-value test.
 *
 * The BrBG ramp is divergent, so the displayed domain is symmetric about
 * 0: the neutral white class must land on ΔNDMI = 0, with brown below it
 * (drying) and teal above it (wetting). The magnitude comes from the data —
 * the 1st/99th percentile snapped up to a 0.05 step — which covers ~99% of
 * the valid cells without letting a handful of extremes flatten the ramp.
 *
 * Source: public/rasters/hydric-anomaly-10m.tif (894x419, float32, LZW)
 * Output: public/rasters/hydric-anomaly-10m.png (BrBG, NaN -> alpha 0)
 *         src/data/hydric-raster.generated.ts (bounds, ramp, stats)
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

import { isValidCell, readTiff } from "./lib/geotiff.mjs";
import {
  asLngLat,
  centerOf,
  encodePng,
  fmt,
  footprintBounds,
  makeSampler,
  percentile,
  sortedValid,
  stepTicks,
} from "./lib/bake.mjs";

const projectRoot = process.cwd();
const SOURCE_TIF = join(projectRoot, "public", "rasters", "hydric-anomaly-10m.tif");
const OUT_PNG = join(projectRoot, "public", "rasters", "hydric-anomaly-10m.png");
const OUT_TS = join(projectRoot, "src", "data", "hydric-raster.generated.ts");

/** Raster-to-metres factor at the equator; the grid is a nominal 10 m. */
const DEGREES_TO_METRES = 111319.49079327358;

/**
 * 11-class diverging Brown-Blue-Green (USDA-style BrBG). Even stops are
 * neutral, so stop 5 (#f5f5f5) sits at the midpoint of a symmetric domain
 * and reads as "no anomaly".
 */
const RAMP = [
  { at: 0.0, hex: "#543005" },
  { at: 0.1, hex: "#8c510a" },
  { at: 0.2, hex: "#bf812d" },
  { at: 0.3, hex: "#dfc27d" },
  { at: 0.4, hex: "#f6e8c3" },
  { at: 0.5, hex: "#f5f5f5" },
  { at: 0.6, hex: "#c7eae5" },
  { at: 0.7, hex: "#80cdc1" },
  { at: 0.8, hex: "#35978f" },
  { at: 0.9, hex: "#01665e" },
  { at: 1.0, hex: "#003c30" },
];

/** Snap the domain outwards to a 0.05 step so the legend labels stay round. */
const STEP = 0.05;

const sampleRamp = makeSampler(RAMP);

function main() {
  let tif;
  try {
    tif = readTiff(readFileSync(SOURCE_TIF));
  } catch (err) {
    if (err.code === "ENOENT") {
      console.warn(
        `[build-hydric-raster] ${relative(projectRoot, SOURCE_TIF)} not found — ` +
          `skipping. The hydric tab degrades to a placeholder.`
      );
      return;
    }
    throw err;
  }

  const { width, height, pixels, nodata, geotransform, crs } = tif;
  if (!geotransform) throw new Error("missing georeferencing");
  if (crs.kind !== "geographic" || crs.epsg !== 4326) {
    throw new Error(`expected geographic EPSG:4326, got ${crs.label ?? "no CRS"}`);
  }

  const valid = sortedValid(pixels, (v) => isValidCell(v, nodata));
  if (valid.length === 0) throw new Error("every cell is nodata");

  const p1 = percentile(valid, 0.01);
  const p99 = percentile(valid, 0.99);
  const magnitude = Math.max(Math.abs(p1), Math.abs(p99));
  let a = Math.ceil(magnitude / STEP - 1e-9) * STEP;
  if (!(a > 0)) a = Math.max(Math.abs(valid[0]), Math.abs(valid[valid.length - 1])) || STEP;
  const lo = -a;
  const hi = a;
  const span = hi - lo;

  /** Value -> 0..1 position on the divergent ramp; 0 lands on white. */
  const normalise = (v) => Math.min(1, Math.max(0, (v - lo) / span));
  const ticks = stepTicks(lo, hi, STEP);

  const rgba = Buffer.alloc(width * height * 4);
  let painted = 0;
  for (let i = 0; i < pixels.length; i++) {
    const v = pixels[i];
    if (!isValidCell(v, nodata)) {
      rgba[i * 4 + 3] = 0;
      continue;
    }
    const [r, g, b] = sampleRamp(normalise(v));
    rgba[i * 4] = r;
    rgba[i * 4 + 1] = g;
    rgba[i * 4 + 2] = b;
    rgba[i * 4 + 3] = 255;
    painted++;
  }

  const png = encodePng(width, height, rgba);
  mkdirSync(dirname(OUT_PNG), { recursive: true });
  writeFileSync(OUT_PNG, png);

  const bounds = footprintBounds(geotransform, width, height, asLngLat);
  const center = centerOf(bounds);
  const pixelSizeDegrees = Math.abs(geotransform.pixelW);

  const body = `/**
 * GENERATED by scripts/build-hydric-raster.mjs — do not edit.
 *
 * Source raster: ${relative(projectRoot, SOURCE_TIF).replace(/\\/g, "/")}
 * Source CRS:    ${crs.label}
 * Colours baked into: ${relative(projectRoot, OUT_PNG).replace(/\\/g, "/")}
 *
 * Divergent domain: the ramp's neutral class is pinned to ΔNDMI 0, with
 * the magnitude taken from the 1st/99th percentile and snapped outwards to
 * a ${STEP} step. Cells beyond it clamp to the ramp ends; trueMin/trueMax
 * keep the raw extremes visible. Masked cells (NaN in the source, since the
 * GeoTIFF carries no GDAL_NODATA tag) bake to alpha 0.
 */

/** Footprint in WGS84 as [west, south, east, north]. */
export const hydricBounds = [${bounds.map((n) => fmt(n, 6)).join(", ")}] as const;

/** Where the camera should sit when the hydric tab opens. */
export const hydricCenter = [${center.map((n) => fmt(n, 6)).join(", ")}] as const;

/** Raster grid, before any client-side styling. */
export const hydricGrid = {
  width: ${width},
  height: ${height},
  /** Nominal ground sample distance; the source is published as a 10 m grid. */
  pixelSizeMetres: ${fmt(pixelSizeDegrees * DEGREES_TO_METRES, 1)},
  pixelSizeDegrees: ${pixelSizeDegrees},
  crs: ${JSON.stringify(crs.label)},
  epsg: ${crs.epsg},
} as const;

export const hydricRange = {
  min: ${fmt(lo)},
  max: ${fmt(hi)},
  median: ${fmt(percentile(valid, 0.5))},
  mean: ${fmt(valid.reduce((x, y) => x + y, 0) / valid.length)},
  trueMin: ${fmt(valid[0], 3)},
  trueMax: ${fmt(valid[valid.length - 1], 3)},
  scale: "linear",
  nodata: ${nodata === null ? '"NaN"' : fmt(nodata, 3)},
  validCells: ${valid.length},
  paintedCells: ${painted},
  unit: "ΔNDMI",
  label: "Hydric anomaly (ΔNDMI)",
} as const;

/** 11-class diverging ramp; the legend gradient is built from these. */
export const hydricRamp = [
${RAMP.map((s) => `  { at: ${s.at}, hex: ${JSON.stringify(s.hex)} },`).join("\n")}
] as const;

/**
 * Legend tick positions, already mapped through the linear scale so the
 * gradient labels sit where those values actually are in the baked PNG.
 */
export const hydricTicks = [
${ticks.map((t) => `  { value: ${t}, at: ${fmt(normalise(t), 4)} },`).join("\n")}
] as const;

/** Default overlay opacity, 0-1. Tuned to sit over the satellite basemap. */
export const hydricDefaultOpacity = 0.8;

export const hydricPngPath = "/rasters/hydric-anomaly-10m.png";
`;

  mkdirSync(dirname(OUT_TS), { recursive: true });
  writeFileSync(OUT_TS, body.replace(/\r\n/g, "\n"), "utf8");

  console.info(
    `[build-hydric-raster] ${width}x${height} -> ${relative(projectRoot, OUT_PNG)} ` +
      `(${png.length} B, ${painted} painted cells)\n` +
      `  bounds ${bounds.map((n) => fmt(n, 4)).join(", ")}\n` +
      `  domain ${fmt(lo)} .. ${fmt(hi)} ΔNDMI (p1 ${fmt(p1, 3)}, p99 ${fmt(p99, 3)}), ` +
      `${ticks.length} ticks`
  );
}

main();
