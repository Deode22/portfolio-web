/**
 * GeoTIFF -> class-colormapped RGBA PNG + generated manifest for the
 * disturbance layer.
 *
 * Same pipeline as the RUSLE bake (scripts/lib/), different display rules:
 * the source is a Google Earth Engine Sentinel-2 disturbance export,
 * classic big-endian TIFF, tiled Adobe Deflate uint8, georeferencing via a
 * ModelTransformation matrix rather than a tiepoint.
 *
 * The band is categorical (0 unaffected / 1 low / 2 moderate / 3 high), so
 * no ramp interpolation happens: each class paints its own colour and the
 * legend renders swatches instead of a gradient.
 *
 * GDAL_NODATA on this file reads "0.0", but that is a mis-declaration, not
 * a mask: class 0 fills 35.8% of the *interior* of the grid (vs 42.6% along
 * the border) with no background ring around the data, which is what a real
 * "unaffected" class looks like and what a masked background never does.
 * The tag is therefore ignored and 0 paints green.
 *
 * Source: public/rasters/disturbance-severity-10m.tif (1660x918, uint8)
 * Output: public/rasters/disturbance-severity-10m.png (4 classes)
 *         src/data/disturbance-raster.generated.ts (bounds, classes, stats)
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

import { readTiff } from "./lib/geotiff.mjs";
import { asLngLat, centerOf, encodePng, fmt, footprintBounds } from "./lib/bake.mjs";

const projectRoot = process.cwd();
const SOURCE_TIF = join(projectRoot, "public", "rasters", "disturbance-severity-10m.tif");
const OUT_PNG = join(projectRoot, "public", "rasters", "disturbance-severity-10m.png");
const OUT_TS = join(projectRoot, "src", "data", "disturbance-raster.generated.ts");

/** Raster-to-metres factor at the equator; the grid is a nominal 10 m. */
const DEGREES_TO_METRES = 111319.49079327358;

/**
 * The four classes, in order. Green -> cream -> orange -> red reads as an
 * escalation on the satellite basemap and stays separable at 30% opacity.
 */
const CLASSES = [
  { value: 0, hex: "#2ca25f", label: "Unaffected / Stable canopy" },
  { value: 1, hex: "#ffeb80", label: "Low disturbance / Defoliation" },
  { value: 2, hex: "#fd8d3c", label: "Moderate severity / Canopy damage" },
  { value: 3, hex: "#bd0026", label: "High severity / Stand loss" },
];

const hexToRgb = (hex) => [
  parseInt(hex.slice(1, 3), 16),
  parseInt(hex.slice(3, 5), 16),
  parseInt(hex.slice(5, 7), 16),
];
const CLASS_RGB = CLASSES.map((c) => hexToRgb(c.hex));

function main() {
  let tif;
  try {
    tif = readTiff(readFileSync(SOURCE_TIF));
  } catch (err) {
    if (err.code === "ENOENT") {
      console.warn(
        `[build-disturbance-raster] ${relative(projectRoot, SOURCE_TIF)} not found — ` +
          `skipping. The disturbance tab degrades to a placeholder.`
      );
      return;
    }
    throw err;
  }

  const { width, height, pixels, geotransform, crs } = tif;
  if (!geotransform) throw new Error("missing georeferencing");
  if (crs.kind !== "geographic" || crs.epsg !== 4326) {
    throw new Error(`expected geographic EPSG:4326, got ${crs.label ?? "no CRS"}`);
  }

  const total = width * height;
  const counts = new Array(CLASSES.length).fill(0);
  let painted = 0;
  const rgba = Buffer.alloc(total * 4);

  for (let i = 0; i < pixels.length; i++) {
    const v = pixels[i];
    // Finite test only: the GDAL_NODATA tag says 0 but class 0 is real data
    // (see the header). Anything outside 0..3 is not a class we can draw.
    const cls = Number.isFinite(v) ? Math.round(v) : -1;
    if (cls < 0 || cls > 3) {
      rgba[i * 4 + 3] = 0;
      continue;
    }
    const [r, g, b] = CLASS_RGB[cls];
    rgba[i * 4] = r;
    rgba[i * 4 + 1] = g;
    rgba[i * 4 + 2] = b;
    rgba[i * 4 + 3] = 255;
    counts[cls]++;
    painted++;
  }

  const png = encodePng(width, height, rgba);
  mkdirSync(dirname(OUT_PNG), { recursive: true });
  writeFileSync(OUT_PNG, png);

  const bounds = footprintBounds(geotransform, width, height, asLngLat);
  const center = centerOf(bounds);
  const pixelSizeDegrees = Math.abs(geotransform.pixelW);

  const body = `/**
 * GENERATED by scripts/build-disturbance-raster.mjs — do not edit.
 *
 * Source raster: ${relative(projectRoot, SOURCE_TIF).replace(/\\/g, "/")}
 * Source CRS:    ${crs.label}
 * Colours baked into: ${relative(projectRoot, OUT_PNG).replace(/\\/g, "/")}
 *
 * Categorical 4-class bake: no ramp, no value interpolation — each class
 * paints its own hex. The source's GDAL_NODATA tag reads "0.0" but class 0
 * is a real "unaffected" class (interior-distributed, no background ring),
 * so the tag is ignored rather than punched through as transparency.
 */

/** Footprint in WGS84 as [west, south, east, north]. */
export const disturbanceBounds = [${bounds.map((n) => fmt(n, 6)).join(", ")}] as const;

/** Where the camera should sit when the disturbance tab opens. */
export const disturbanceCenter = [${center.map((n) => fmt(n, 6)).join(", ")}] as const;

/** Raster grid, before any client-side styling. */
export const disturbanceGrid = {
  width: ${width},
  height: ${height},
  /** Nominal ground sample distance; the source is published as a 10 m grid. */
  pixelSizeMetres: ${fmt(pixelSizeDegrees * DEGREES_TO_METRES, 1)},
  pixelSizeDegrees: ${pixelSizeDegrees},
  crs: ${JSON.stringify(crs.label)},
  epsg: ${crs.epsg},
} as const;

export const disturbanceRange = {
  min: 0,
  max: 3,
  scale: "categorical",
  nodata: null,
  validCells: ${painted},
  paintedCells: ${painted},
  unit: "class",
  label: "Disturbance severity class (0–3)",
} as const;

/** The four classes in escalation order; the legend renders swatches. */
export const disturbanceClasses = [
${CLASSES.map(
  (c) =>
    `  { value: ${c.value}, hex: ${JSON.stringify(c.hex)}, label: ${JSON.stringify(c.label)}, ` +
    `count: ${counts[c.value]}, share: ${fmt((counts[c.value] / total) * 100, 1)} },`
).join("\n")}
] as const;

/** Categorical layers have no gradient; kept so the spec shape stays uniform. */
export const disturbanceRamp = [
${CLASSES.map((c, i) => `  { at: ${fmt(i / 3, 4)}, hex: ${JSON.stringify(c.hex)} },`).join("\n")}
] as const;

export const disturbanceTicks = [] as const;

/** Default overlay opacity, 0-1. 30% opacity keeps the severity classes legible over the basemap. */
export const disturbanceDefaultOpacity = 0.3;

export const disturbancePngPath = "/rasters/disturbance-severity-10m.png";
`;

  mkdirSync(dirname(OUT_TS), { recursive: true });
  writeFileSync(OUT_TS, body.replace(/\r\n/g, "\n"), "utf8");

  console.info(
    `[build-disturbance-raster] ${width}x${height} -> ${relative(projectRoot, OUT_PNG)} ` +
      `(${png.length} B, ${painted} painted cells)\n` +
      `  bounds ${bounds.map((n) => fmt(n, 4)).join(", ")}\n` +
      `  classes ${counts.map((n, i) => `${i}:${n}`).join(" ")} (${total} cells)`
  );
}

main();
